"""Property-based tests for the WRF run description.

apps/WRF/lib/wrf-run-info.sh gives the WRF benchmark scripts what makes two
runs comparable, for the recorder: domain 1's grid size (e_we x e_sn x e_vert,
in millions), the simulated minutes (run_days, run_hours, run_minutes and
run_seconds when one of them is above 0, else domain 1's end date minus its
start date), the history output's io_form, and the number of domain-1 steps in
rsl.error.0000. A namelist key is read only from a line that starts with it,
and only when one line names it; a value that cannot be read is left out.

These tests run the bash function itself, the way the benchmark scripts call
it, on run directories generated by Hypothesis (synthetic values only), and
compare its output with the reference below.

Run with:
    python -m pip install -r tests/requirements.txt
    python -m pytest tests/test_wrf_run_info.py -q
"""
from __future__ import annotations

import datetime as dt
import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest
from hypothesis import given, settings, strategies as st

REPO = Path(__file__).resolve().parents[1]
LIB = REPO / "apps" / "WRF" / "lib" / "wrf-run-info.sh"

pytestmark = pytest.mark.skipif(shutil.which("bash") is None, reason="needs bash")

GRID = ("e_we", "e_sn", "e_vert")
RUN = (("run_days", 86400), ("run_hours", 3600), ("run_minutes", 60), ("run_seconds", 1))
DATE = ("year", "month", "day", "hour", "minute", "second")

# How a namelist line can set a key ({k} the key, {K} in capitals, {v} domain
# 1's value). The library reads the first forms, and none of the others.
READ = ("{k} = {v},", "{K} = {v}, {v},", "{k} = 2*{v},", "{k}={v} ! a comment", "{k} = {v} {v}")
NOT_READ = ("io_form_input = 2, {k} = {v},", "{k}(1) = {v},", "{k} =\n {v},", "{k} = 3* {v},")


@st.composite
def runs(draw):
    """A run directory's namelist (key -> (value, form), form None: absent) and step count."""
    keys = {}

    def put(key, value):
        form = draw(st.one_of(st.none(), st.sampled_from(READ), st.sampled_from(READ), st.sampled_from(NOT_READ)))
        keys[key] = (value, form)

    for key in GRID:
        put(key, draw(st.integers(min_value=0, max_value=3000)))
    for key, _ in RUN:
        put(key, draw(st.one_of(st.just(0), st.integers(min_value=0, max_value=3))))
    start = draw(st.datetimes(min_value=dt.datetime(1990, 1, 1), max_value=dt.datetime(2100, 12, 31)))
    start = start.replace(microsecond=0)
    end = start + dt.timedelta(seconds=draw(st.integers(min_value=-3600, max_value=4 * 86400)))
    for prefix, t in (("start", start), ("end", end)):
        for field, value in zip(DATE, (t.year, t.month, t.day, t.hour, t.minute, t.second)):
            put(f"{prefix}_{field}", value)
    put("io_form_history", draw(st.sampled_from((2, 11, 102))))
    return {"keys": keys, "twice": draw(st.sampled_from([None, *keys])),
            "steps": draw(st.integers(min_value=0, max_value=30))}


def write(run, d: Path) -> None:
    lines = [" &time_control"]
    for key, (value, form) in run["keys"].items():
        if form is None:
            continue
        text = " " + form.format(k=key, K=key.upper(), v=value)
        lines.append(text)
        if run["twice"] == key:
            lines.append(text)
    lines.append(" /")
    (d / "namelist.input").write_text("\n".join(lines) + "\n")
    steps = [f"Timing for main: time 2000-01-01_00:00:{n:02d} on domain   1:    1.00000 elapsed seconds"
             for n in range(run["steps"])]
    steps.append("Timing for main: time 2000-01-01_00:00:05 on domain   2:    0.50000 elapsed seconds")
    (d / "rsl.error.0000").write_text("\n".join(steps) + "\n")


def read(run, key):
    """('unset' | 'ok' | 'bad', value) as the library documents it."""
    value, form = run["keys"].get(key, (None, None))
    if form is None:
        return "unset", None
    if run["twice"] == key or form not in READ:
        return "bad", None
    return "ok", value


def reference(run) -> str:
    out = []
    grid = [read(run, key) for key in GRID]
    if all(state == "ok" and value > 0 for state, value in grid):
        out.append(f"num_cells_million={grid[0][1] * grid[1][1] * grid[2][1] / 1e6:.3f}")
    seconds, good = 0, True
    for key, factor in RUN:
        state, value = read(run, key)
        if state == "unset":
            continue
        if state == "bad":
            good = False
            break
        seconds += value * factor
    if good and seconds == 0:
        stamps = []
        for prefix in ("start", "end"):
            fields = [read(run, f"{prefix}_{field}") for field in DATE]
            if all(state == "ok" for state, _ in fields):
                stamps.append(dt.datetime(*(value for _, value in fields)))
        if len(stamps) == 2 and stamps[1] > stamps[0]:
            seconds = int((stamps[1] - stamps[0]).total_seconds())
    if good and seconds > 0:
        out.append(f"simulated_minutes={seconds // 60}" if seconds % 60 == 0
                   else f"simulated_minutes={seconds / 60:.3f}")
    state, value = read(run, "io_form_history")
    if state == "ok":
        out.append(f"io_form={value}")
    if run["steps"]:
        out.append(f"num_timesteps={run['steps']}")
    return "".join(line + "\n" for line in out)


def run_info(d: Path) -> str:
    """Run the function as the benchmark scripts do, under set -euo pipefail."""
    result = subprocess.run(["bash", "-c", 'set -euo pipefail; . "$1"; wrf_run_info "$2"', "_", str(LIB), str(d)],
                            capture_output=True, text=True, check=True)
    return result.stdout


@settings(max_examples=200)
@given(run=runs())
def test_run_info_matches_reference(run):
    """Every value the namelist and the log give, and none they do not."""
    with tempfile.TemporaryDirectory() as tmp:
        write(run, Path(tmp))
        assert run_info(Path(tmp)) == reference(run)


@settings(max_examples=50)
@given(run=runs())
def test_a_namelist_it_reads_gives_every_value(run):
    """With every key set once, in a form it reads, the grid, the length and io_form are all given."""
    run = dict(run, twice=None, keys={key: (value, READ[0]) for key, (value, _) in run["keys"].items()})
    with tempfile.TemporaryDirectory() as tmp:
        write(run, Path(tmp))
        got = run_info(Path(tmp))
    assert got == reference(run)
    assert "io_form=" in got
