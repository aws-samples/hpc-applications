"""Property-based tests for the WRF run check.

apps/WRF/lib/wrf-run-check.sh decides whether a WRF benchmark run is
recorded: rank 0's rsl.error.0000 must say "SUCCESS COMPLETE WRF", every
history file of domain 1 that WRF wrote must be in the run directory and not
empty, and there must be at least as many restart files of domain 1
(wrfrst_d01_*) as WRF made restart writes, none of them empty. Which history
files WRF wrote comes from its "Timing for Writing wrfout_d01_<date>" lines:
WRF puts frames_per_outfile writes (namelist.input; WRF's default is 10) in
each file, named after the first of them. The line gives the name WRF made
(with nocolons = .true., an '_' for each ':'); serial netCDF
(io_form_history = 2, WRF's default) writes the file under it, PnetCDF (11)
with an '_' for each ':' in it. The check reads frames_per_outfile and
io_form_history only from a line that starts with each, and refuses a
namelist that names either in another form rather than take the default.

These tests run the bash function itself, the way the benchmark scripts call
it, on run directories generated by Hypothesis (synthetic times only), and
compare its verdict and its problems with the reference below.

Run with:
    python -m pip install -r tests/requirements.txt
    python -m pytest tests/test_wrf_run_check.py -q
"""
from __future__ import annotations

import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest
from hypothesis import given, settings, strategies as st

REPO = Path(__file__).resolve().parents[1]
LIB = REPO / "apps" / "WRF" / "lib" / "wrf-run-check.sh"

pytestmark = pytest.mark.skipif(shutil.which("bash") is None, reason="needs bash")

SUCCESS = "d01 2000-01-02_00:00:00 wrf: SUCCESS COMPLETE WRF"
# Lines the check must ignore: steps, domain 2's writes, other messages.
NOISE = (
    "Timing for main: time 2000-01-01_00:00:15 on domain   1:    1.00000 elapsed seconds",
    "Timing for main (dt= 15.00): time 2000-01-01_00:00:30 on domain   1:    1.00000 elapsed seconds",
    "Timing for Writing wrfout_d02_2000-01-01_00:00:00 for domain        2:    3.00000 elapsed seconds",
    "Timing for Writing restart for domain        2:    4.00000 elapsed seconds",
    "Timing for processing lateral boundary for domain        1:    0.50000 elapsed seconds",
    "d01 2000-01-01_00:00:00  Input data is acceptable to use: wrfbdy_d01",
)


def history_name(k: int, sep: str = ":") -> str:
    """The k-th history write's file name (one write an hour), sep between its hour, minute and second."""
    return f"wrfout_d01_2000-01-{1 + k // 24:02d}_{k % 24:02d}{sep}00{sep}00"


def restart_name(k: int, sep: str = ":") -> str:
    return f"wrfrst_d01_2000-01-01_{k:02d}{sep}00{sep}00"


# The namelist line that sets frames_per_outfile ({f}: domain 1's value). The
# check reads it from a line that starts with it, "frames_per_outfile = <n>[,
# ...]", in any case, a repeat count <r>*<n> reading as <n>; it refuses any
# other line that names the key rather than take WRF's default.
READABLE = (
    "frames_per_outfile = {f}, 1,",
    "FRAMES_PER_OUTFILE = {f} 1",
    "frames_per_outfile = 2*{f},",
    "frames_per_outfile = {f} ! frames per file",
)
UNREADABLE = (
    "history_interval = 60, frames_per_outfile = {f},",
    "frames_per_outfile(1) = {f},",
    "frames_per_outfile =\n {f},",
)
# The same for io_form_history ({v}: its value; the key has one, not one per domain).
IO_READABLE = (
    "io_form_history = {v},",
    "IO_FORM_HISTORY = {v}",
    "io_form_history = 1*{v},",
    "io_form_history = {v} ! output format",
)
IO_UNREADABLE = (
    "io_form_restart = 2, io_form_history = {v},",
    "io_form_history(1) = {v},",
    "io_form_history =\n {v},",
)


def wrf_sep(run) -> str:
    """What WRF writes between the hour, minute and second of a file's name in this run."""
    return "_" if run["nocolons"] or run["io"] == 11 else ":"


@st.composite
def runs(draw):
    """A run directory: its log, its namelist and the files WRF left there."""
    n_history = draw(st.integers(min_value=0, max_value=14))
    n_restart = draw(st.integers(min_value=0, max_value=3))
    events = ["H"] * n_history + ["R"] * n_restart + draw(st.lists(st.sampled_from(NOISE), max_size=6))
    events = draw(st.permutations(events))
    # None: the namelist does not set frames_per_outfile (WRF's default, 10).
    frames = draw(st.one_of(st.none(), st.integers(min_value=1, max_value=5)))
    form = draw(st.sampled_from(READABLE + UNREADABLE))
    # None: the namelist does not set io_form_history (WRF's default, 2: serial netCDF).
    io = draw(st.one_of(st.none(), st.sampled_from((2, 11))))
    io_form = draw(st.sampled_from(IO_READABLE + IO_UNREADABLE))
    run = {"success": draw(st.booleans()), "events": events, "frames": frames, "form": form, "io": io,
           "io_form": io_form, "nocolons": draw(st.booleans()), "namelist": draw(st.booleans()),
           "n_history": n_history, "n_restart": n_restart}
    sep = wrf_sep(run)
    files = {}
    for k in range(n_history):  # every history write's name, in or out of a file
        state = draw(st.sampled_from(("ok", "ok", "ok", "missing", "empty")))
        if state != "missing":
            # Mostly the name WRF writes; sometimes the one with the other separator.
            other = draw(st.sampled_from((False, False, True)))
            files[history_name(k, (":" if sep == "_" else "_") if other else sep)] = state
    restarts = draw(st.lists(st.sampled_from(("ok", "ok", "empty")), max_size=n_restart + 1))
    for k, state in enumerate(restarts):
        files[restart_name(k, sep)] = state
    return dict(run, files=files, restarts=restarts)


def write(run, d: Path) -> None:
    lines, k = [], 0
    log_sep = "_" if run["nocolons"] else ":"  # the log gives the name WRF made
    for e in run["events"]:
        if e == "H":
            lines.append(f"Timing for Writing {history_name(k, log_sep)} for domain        1:    3.00000 elapsed seconds")
            k += 1
        elif e == "R":
            lines.append("Timing for Writing restart for domain        1:    4.00000 elapsed seconds")
        else:
            lines.append(e)
    if run["success"]:
        lines.append(SUCCESS)
    (d / "rsl.error.0000").write_text("".join(line + "\n" for line in lines))
    if run["namelist"]:
        text = " &time_control\n run_hours = 6,\n"
        if run["frames"] is not None:
            text += " " + run["form"].format(f=run["frames"]) + "\n"
        if run["io"] is not None:
            text += " " + run["io_form"].format(v=run["io"]) + "\n"
        if run["nocolons"]:
            text += " nocolons = .true.,\n"
        (d / "namelist.input").write_text(text + " /\n")
    for name, state in run["files"].items():
        (d / name).write_text("" if state == "empty" else "stub output\n")


def reference(run) -> set[str]:
    """The problems the check documents, as a set (their order is not part of the rule)."""
    problems = set()
    if not run["success"]:
        problems.add("rsl.error.0000 does not say SUCCESS COMPLETE WRF")
    if run["n_history"]:
        if not run["namelist"]:
            problems.add("no namelist.input to tell which history files WRF wrote")
        else:
            readable = True
            if run["frames"] is not None and run["form"] in UNREADABLE:
                line = run["form"].format(f=run["frames"]).split("\n")[0].strip()
                problems.add(f"cannot read frames_per_outfile from namelist.input ('{line}')")
                readable = False
            if run["io"] is not None and run["io_form"] in IO_UNREADABLE:
                line = run["io_form"].format(v=run["io"]).split("\n")[0].strip()
                problems.add(f"cannot read io_form_history from namelist.input ('{line}')")
                readable = False
            if readable:
                for k in range(0, run["n_history"], run["frames"] or 10):
                    name = history_name(k, wrf_sep(run))
                    state = run["files"].get(name, "missing")
                    if state != "ok":
                        problems.add(f"history file {name} is {state}")
    for k, state in enumerate(run["restarts"]):
        if state == "empty":
            problems.add(f"restart file {restart_name(k, wrf_sep(run))} is empty")
    if len(run["restarts"]) < run["n_restart"]:
        problems.add(f"{run['n_restart']} restart write(s) in rsl.error.0000 but "
                     f"{len(run['restarts'])} wrfrst_d01_* file(s)")
    return problems


def check(d: Path) -> tuple[int, set[str]]:
    """Run the check as the benchmark scripts do: in an if, under set -euo pipefail."""
    script = ('set -euo pipefail; . "$1"; if out=$(wrf_run_check "$2"); then rc=0; else rc=1; fi; '
              + 'printf "%s\\n%s" "$rc" "$out"')
    result = subprocess.run(["bash", "-c", script, "_", str(LIB), str(d)],
                            capture_output=True, text=True, check=True)
    rc, _, out = result.stdout.partition("\n")
    return int(rc), {line for line in out.splitlines() if line}


@settings(max_examples=200)
@given(run=runs())
def test_run_check_matches_reference(run):
    """Passes exactly when the reference finds no problem, and names every problem it finds."""
    with tempfile.TemporaryDirectory() as tmp:
        write(run, Path(tmp))
        rc, problems = check(Path(tmp))
        want = reference(run)
        assert problems == want
        assert rc == (1 if want else 0)


@settings(max_examples=50)
@given(run=runs())
def test_a_complete_run_with_all_its_files_passes(run):
    """SUCCESS COMPLETE WRF, a namelist it reads, every history file under the name WRF writes, and a
    non-empty file per restart write."""
    run = dict(run, success=True, namelist=True,
               form=run["form"] if run["form"] in READABLE else READABLE[0],
               io_form=run["io_form"] if run["io_form"] in IO_READABLE else IO_READABLE[0],
               restarts=["ok"] * run["n_restart"])
    sep = wrf_sep(run)
    run["files"] = {history_name(k, sep): "ok" for k in range(run["n_history"])}
    run["files"].update({restart_name(k, sep): "ok" for k in range(run["n_restart"])})
    with tempfile.TemporaryDirectory() as tmp:
        write(run, Path(tmp))
        assert check(Path(tmp)) == (0, set())
